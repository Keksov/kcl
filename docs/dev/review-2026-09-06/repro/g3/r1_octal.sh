echo -n "tryISOStrToDate via _valid_date is safe? tryISOStrToDate 'x[\$(echo INJ3>&2)]' -> "; dateutils.tryISOStrToDate 'x[$(echo INJ3>&2)]'; echo " rc=$?"
echo -n "compareDateTime 'a[\$(echo INJ4>&2)]' 0 -> "; dateutils.compareDateTime 'a[$(echo INJ4>&2)]' 0; echo " rc=$?"
