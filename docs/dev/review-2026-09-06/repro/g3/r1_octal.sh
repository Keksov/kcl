echo "bash $BASH_VERSION"
echo "--- leading-zero (octal) inputs"
echo -n "encodeDate 2011 08 09 -> "; dateutils.encodeDate 2011 08 09; echo " rc=$?"
echo -n "encodeDate 2011 07 09 -> "; dateutils.encodeDate 2011 07 09; echo " rc=$?"
echo -n "encodeTime 09 05 08 000 -> "; dateutils.encodeTime 09 05 08 000; echo " rc=$?"
echo -n "isValidDate 2011 08 15 -> "; dateutils.isValidDate 2011 08 15; echo " rc=$?"
echo -n "daysInAMonth 2011 09 -> "; dateutils.daysInAMonth 2011 09; echo " rc=$?"
