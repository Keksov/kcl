# fv.unicode._expand PAGE — __FV_UC_E[PAGE*16 .. PAGE*16+15] from __FV_UC_M[PAGE]
fv.unicode._expand() {
    local __fvu_s=${__FV_UC_M[$1]} __fvu_o='' __fvu_k __fvu_n __fvu_p __fvu_i
    while [[ -n $__fvu_s ]]; do
        __fvu_k=${__fvu_s:0:1} __fvu_s=${__fvu_s:1}
        __fvu_n=${__fvu_s%%[!0123456789]*}
        __fvu_s=${__fvu_s:${#__fvu_n}}
        printf -v __fvu_p '%*s' "$__fvu_n" ''
        __fvu_o+=${__fvu_p// /$__fvu_k}
    done
    for (( __fvu_i = 0; __fvu_i < 16; __fvu_i++ )); do
        __FV_UC_E[$1 * 16 + __fvu_i]=${__fvu_o:__fvu_i * 16:16}
    done
}

# fv.unicode.charClass CP — RESULT = the class letter (z n w x y m r)
fv.unicode.charClass() {
    if [[ -z ${1-} || $1 == *[!0123456789]* || ${#1} -gt 7 ]]; then
        kk.debug "Error: fv.unicode.charClass: not a code point: '${1-}'"
        RESULT=''
        return 2
    fi
    if (( 10#$1 > 1114111 )); then
        kk.debug "Error: fv.unicode.charClass: $1 is above U+10FFFF"
        RESULT=''
        return 1
    fi
    RESULT=${__FV_UC_P[10#$1 >> 14]:10#$1 / 256 % 64:1}
    if [[ $RESULT == '*' ]]; then
        if [[ -z ${__FV_UC_E[10#$1 >> 4]-} ]]; then fv.unicode._expand "$(( 10#$1 >> 8 ))"; fi
        RESULT=${__FV_UC_E[10#$1 >> 4]:10#$1 % 16:1}
    fi
}

# fv.unicode.charWidth CP — RESULT = 0, 1 or 2
fv.unicode.charWidth() {
    fv.unicode.charClass "$@" || return
    RESULT=${__FV_UC_W[$RESULT]}
}

# fv.unicode.version — RESULT = the Unicode version of the table (16.0.0)
fv.unicode.version() {
    RESULT=$__FV_UC_VERSION
}
